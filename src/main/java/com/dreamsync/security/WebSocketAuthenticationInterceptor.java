package com.dreamsync.security;

import com.dreamsync.entity.User;
import com.dreamsync.repository.UserRepository;
import io.jsonwebtoken.JwtException;
import org.springframework.messaging.Message;
import org.springframework.messaging.MessageChannel;
import org.springframework.messaging.MessageDeliveryException;
import org.springframework.messaging.simp.stomp.StompCommand;
import org.springframework.messaging.simp.stomp.StompHeaderAccessor;
import org.springframework.messaging.support.ChannelInterceptor;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.core.authority.SimpleGrantedAuthority;
import org.springframework.stereotype.Component;

import java.util.List;

@Component
public class WebSocketAuthenticationInterceptor implements ChannelInterceptor {

    private static final String PRIVATE_NOTIFICATION_DESTINATION = "/user/queue/notifications";

    private final JwtService jwtService;
    private final UserRepository userRepository;

    public WebSocketAuthenticationInterceptor(JwtService jwtService, UserRepository userRepository) {
        this.jwtService = jwtService;
        this.userRepository = userRepository;
    }

    @Override
    public Message<?> preSend(Message<?> message, MessageChannel channel) {
        StompHeaderAccessor accessor = StompHeaderAccessor.wrap(message);
        StompCommand command = accessor.getCommand();

        if (command == StompCommand.CONNECT) {
            authenticate(accessor);
        } else if (command == StompCommand.SEND) {
            requireAuthenticated(accessor);
            // Notifications are generated by trusted backend services, never by clients.
            throw new MessageDeliveryException("Client messages are not allowed");
        } else if (command == StompCommand.SUBSCRIBE) {
            requireAuthenticated(accessor);
            if (!PRIVATE_NOTIFICATION_DESTINATION.equals(accessor.getDestination())) {
                throw new MessageDeliveryException("Destination is not allowed");
            }
        }
        return message;
    }

    private void requireAuthenticated(StompHeaderAccessor accessor) {
        if (accessor.getUser() == null) {
            throw new MessageDeliveryException("Authentication required");
        }
    }

    private void authenticate(StompHeaderAccessor accessor) {
        List<String> headers = accessor.getNativeHeader("Authorization");
        if (headers == null || headers.isEmpty() || !headers.get(0).startsWith("Bearer ")) {
            throw new MessageDeliveryException("Bearer token required");
        }

        try {
            String token = headers.get(0).substring(7);
            String email = jwtService.extractEmail(token);
            User user = userRepository.findByEmail(email)
                    .orElseThrow(() -> new MessageDeliveryException("Invalid token"));

            if (!jwtService.isTokenValid(token, user.getEmail())) {
                throw new MessageDeliveryException("Invalid token");
            }

            // Use email as Principal.getName() so convertAndSendToUser targets this account.
            accessor.setUser(new UsernamePasswordAuthenticationToken(
                    user.getEmail(), null,
                    List.of(new SimpleGrantedAuthority("ROLE_" + user.getRole().name()))));
        } catch (JwtException | IllegalArgumentException exception) {
            throw new MessageDeliveryException("Invalid or expired token");
        }
    }
}
